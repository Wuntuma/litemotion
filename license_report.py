#!/usr/bin/env python3
"""Generate docs/THIRD_PARTY_LICENSES.md from `cargo metadata`.

Covers every crate that ends up in a build for ANY platform (normal + build
dependencies; dev-only crates are excluded) and flags licences that are not
plainly permissive so a human can read them. This lists the licence names
cargo knows about; it does not replace reading the licence texts when you ship.
Usage: python3 scripts/license_report.py
"""
import json, subprocess, sys, collections

meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked"], text=True))
pk = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
members = set(meta["workspace_members"])

seen, stack = set(), list(members)
while stack:
    i = stack.pop()
    if i in seen:
        continue
    seen.add(i)
    for d in nodes[i]["deps"]:
        # dep_kinds: kind None = normal, "build", "dev". Skip deps that are dev-only.
        if any(k["kind"] != "dev" for k in d["dep_kinds"]):
            stack.append(d["pkg"])

PERMISSIVE = ("MIT", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Zlib", "Unicode-3.0", "Unicode-DFS-2016", "CC0-1.0", "0BSD", "MIT-0", "BSL-1.0", "Unlicense", "OFL-1.1", "LicenseRef-UFL-1.0", "NCSA", "bzip2-1.0.6", "Ubuntu-font-1.0", "MPL-2.0")

def parts(expr):
    for t in expr.replace("(", " ").replace(")", " ").replace("/", " OR ").split():
        if t not in ("OR", "AND", "WITH"):
            yield t

rows, flagged = [], []
for i in sorted(seen - members, key=lambda i: (pk[i]["name"], pk[i]["version"])):
    p = pk[i]
    lic = p.get("license") or ("see " + (p.get("license_file") or "package"))
    rows.append((p["name"], p["version"], lic))
    # An OR expression is fine if ANY alternative is permissive.
    alts = [a.strip() for a in lic.replace("/", " OR ").split(" OR ")]
    ok = any(all(t in PERMISSIVE or t in ("AND", "WITH") or t.startswith("LLVM") for t in parts(a)) for a in alts) and not lic.startswith("see ")
    if not ok:
        flagged.append((p["name"], p["version"], lic))
    elif any(t == "MPL-2.0" for t in parts(lic)) and not any("MIT" in a or "Apache" in a for a in alts):
        flagged.append((p["name"], p["version"], lic + "  (weak copyleft, file-level)"))

count = collections.Counter(r[2] for r in rows)
out = ["# Third-party licences", "", "Generated by `scripts/license_report.py` from the locked dependency graph (all platforms, normal and build dependencies; dev-only crates excluded). Re-run after changing dependencies.", ""]
out += ["## Bundled in the source tree", "",
        "| Component | Where | Licence |", "|---|---|---|",
        "| miniaudio v0.11.25 | `crates/audio/csrc/miniaudio.h` | Public domain or MIT-0 (your choice) |",
        "| DejaVu fonts | `crates/engine/assets/fonts/` | Bitstream Vera / DejaVu licence (`LICENSE-DejaVu.txt`) |", "",
        "## FFmpeg (not bundled by this repository)", "",
        "LiteMotion runs `ffmpeg` and `ffprobe` as separate programs. Their licence depends on how that FFmpeg was built: builds with libx264 are GPL; LGPL builds exist but lack x264. If you ship FFmpeg with LiteMotion you must comply with its licence (source offer, notices). LiteMotion's own code does not link FFmpeg.", ""]
out += ["## Needs a human look", ""]
if flagged:
    out += ["| Crate | Version | Licence |", "|---|---|---|"] + [f"| {n} | {v} | {l} |" for n, v, l in flagged]
else:
    out += ["None: every dependency offers a permissive licence option."]
out += ["", "## Licence summary", "", "| Licence expression | Crates |", "|---|---|"] + [f"| {k} | {v} |" for k, v in count.most_common()]
out += ["", f"## All {len(rows)} dependencies", "", "| Crate | Version | Licence |", "|---|---|---|"] + [f"| {n} | {v} | {l} |" for n, v, l in rows]
open("docs/THIRD_PARTY_LICENSES.md", "w").write("\n".join(out) + "\n")
print(f"{len(rows)} dependencies; {len(flagged)} flagged")
for f in flagged:
    print("  FLAG", f)
